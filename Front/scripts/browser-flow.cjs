// Run with playwright-cli run-code --filename=scripts/browser-flow.cjs.
// This is a browser QA scenario, not an application backend or learning video.
async (page) => {
  const assert = (value, message) => { if (!value) throw new Error(message); };
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto('http://127.0.0.1:5173/admin/contents');
  await page.getByRole('heading', { name: /^학습 콘텐츠 \d+$/ }).waitFor();
  await page.screenshot({ path: 'output/playwright/01-contents-desktop.png', fullPage: true });
  await page.getByRole('link', { name: '과정 관리', exact: true }).click();
  await page.getByRole('heading', { name: '신입 직장인을 위한 엑셀 기초' }).waitFor();
  await page.screenshot({ path: 'output/playwright/02-courses-desktop.png', fullPage: true });
  await page.getByRole('link', { name: '과정 등록', exact: true }).click();
  await page.getByLabel('과정명').fill('브라우저 검증용 과정');
  await page.getByLabel('과정 소개').fill('등록과 수정 API 연결 화면을 확인하는 예시 과정입니다.');
  await page.getByLabel('학습 목표').fill('관리자 화면의 저장 흐름을 확인합니다.');
  await page.screenshot({ path: 'output/playwright/03-course-form.png', fullPage: true });
  await page.getByRole('button', { name: '과정 등록 저장' }).click();
  await page.waitForURL(url => /\/admin\/courses\/[^/]+$/.test(url.pathname) && !url.pathname.endsWith('/new'));
  await page.reload();
  await page.getByLabel('과정명').waitFor();
  assert(await page.getByLabel('과정명').inputValue() === '브라우저 검증용 과정', '과정 새로고침 복원 실패');
  await page.getByLabel('과정 소개').fill('수정 후 저장한 과정 소개');
  await page.getByRole('button', { name: '수정 저장' }).click();
  await page.getByRole('status').filter({ hasText: '과정이 저장되었습니다.' }).waitFor();
  await page.getByRole('link', { name: '콘텐츠 관리', exact: true }).click();
  await page.getByRole('link', { name: '콘텐츠 등록', exact: true }).click();
  await page.getByRole('button', { name: '공개하기', exact: true }).waitFor();
  await page.getByRole('button', { name: '공개하기', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: '공개에 필요한 항목' }).waitFor();
  assert(await page.getByRole('textbox', {name:'콘텐츠 제목',exact:true}).getAttribute('aria-invalid') === 'true', '필드 오류 연결 누락');
  assert(await page.getByRole('alert').evaluate(el => el === document.activeElement), '오류 요약 포커스 누락');
  await page.screenshot({ path: 'output/playwright/04-publish-validation.png', fullPage: true });
  await page.getByLabel('소속 과정').selectOption('excel-basics');
  await page.getByRole('textbox', { name: '콘텐츠 제목', exact: true }).fill('브라우저 검증 · SUMIF 실습');
  await page.getByLabel('학습 목표', { exact: true }).fill('조건에 맞는 데이터의 합계를 구할 수 있습니다.');
  await page.getByLabel('퀴즈 문제').fill('특정 부서의 매출만 합산하는 함수는?');
  for (const [i, text] of ['SUMIF', 'COUNT', 'MAX', 'MIN'].entries()) await page.getByRole('textbox', { name: `보기 ${i + 1}`, exact: true }).fill(text);
  await page.getByRole('radio', { name: '보기 1 정답', exact: true }).check();
  await page.getByLabel('정답 해설').fill('SUMIF는 조건에 맞는 셀의 값을 합산합니다.');
  await page.getByLabel('선택 실습 안내').fill('예제의 부서별 매출 합계를 계산해 보세요.');
  // Generate an explicitly marked local QA video using the browser's MP4 encoder.
  await page.bringToFront();
  assert(await page.evaluate(() => MediaRecorder.isTypeSupported('video/mp4')), 'MP4 MediaRecorder 지원 필요');
  const downloadPromise = page.waitForEvent('download');
  await page.evaluate(async () => {
    const canvas = document.createElement('canvas'); canvas.width = 360; canvas.height = 640; document.body.append(canvas);
    const ctx = canvas.getContext('2d');
    const draw = () => { ctx.fillStyle = '#1e5040'; ctx.fillRect(0, 0, 360, 640); ctx.fillStyle = '#d8edcf'; ctx.font = '18px sans-serif'; ctx.fillText('EXCEL / 01', 32, 70); ctx.fillStyle = '#fff'; ctx.font = 'bold 48px sans-serif'; ctx.fillText('SUMIF', 32, 285); ctx.font = '18px sans-serif'; ctx.fillText('LOCAL QA VIDEO', 32, 550); };
    draw(); const stream = canvas.captureStream(15); const chunks = [];
    const recorder = new MediaRecorder(stream, { mimeType: 'video/mp4' });
    recorder.ondataavailable = event => chunks.push(event.data);
    const stopped = new Promise(resolve => { recorder.onstop = resolve; });
    recorder.start(); const interval = setInterval(() => { draw(); ctx.font = '12px sans-serif'; ctx.fillText(String(Date.now()), 32, 590); stream.getVideoTracks()[0].requestFrame?.(); }, 60); await new Promise(resolve => setTimeout(resolve, 2400));
    recorder.requestData(); recorder.stop(); await stopped; clearInterval(interval); stream.getTracks().forEach(track => track.stop()); canvas.remove();
    if (!chunks.some(chunk => chunk.size > 0)) throw new Error('QA 영상 프레임을 기록하지 못했습니다. 브라우저를 전면에 두고 다시 실행해 주세요.');
    const url = URL.createObjectURL(new Blob(chunks, { type: 'video/mp4' })); const link = document.createElement('a'); link.href = url; link.download = 'qa-demo.mp4'; link.click(); setTimeout(() => URL.revokeObjectURL(url), 3000);
  });
  await (await downloadPromise).saveAs('output/playwright/qa-demo.mp4');
  await page.getByLabel('숏폼 영상 파일 선택', { exact: true }).setInputFiles('output/playwright/qa-demo.mp4');
  await page.getByText('qa-demo.mp4', { exact: true }).waitFor();
  await page.getByLabel('썸네일 파일 선택', { exact: true }).setInputFiles('public/favicon.svg');
  await page.getByRole('alert').filter({ hasText: '지원하지 않는 파일 형식' }).waitFor();
  // Canvas produces a valid PNG without any network image dependency.
  const thumbnailDownload = page.waitForEvent('download');
  await page.evaluate(() => { const canvas = document.createElement('canvas'); canvas.width = 640; canvas.height = 360; const ctx = canvas.getContext('2d'); ctx.fillStyle = '#e9efdf'; ctx.fillRect(0, 0, 640, 360); ctx.fillStyle = '#205847'; ctx.font = 'bold 60px sans-serif'; ctx.fillText('SUMIF', 60, 190); ctx.font = '20px sans-serif'; ctx.fillText('LOCAL QA THUMBNAIL', 60, 280); const link = document.createElement('a'); link.href = canvas.toDataURL('image/png'); link.download = 'qa-thumbnail.png'; link.click(); });
  await (await thumbnailDownload).saveAs('output/playwright/qa-thumbnail.png');
  await page.getByLabel('썸네일 파일 선택', { exact: true }).setInputFiles('output/playwright/qa-thumbnail.png');
  await page.getByText('qa-thumbnail.png', { exact: true }).waitFor();
  await page.getByLabel('실습 예제 파일 파일 선택').setInputFiles({ name: '실습예제.csv', mimeType: 'text/csv', buffer: Buffer.from('department,sales\nA,100\nB,200\nA,300') });
  await page.getByText('실습예제.csv', { exact: true }).waitFor();
  await page.getByLabel('업무용 템플릿 파일 선택').setInputFiles({ name: '업무템플릿.txt', mimeType: 'text/plain', buffer: Buffer.from('업무 활용 템플릿 예시') });
  await page.getByText('업무템플릿.txt', { exact: true }).waitFor();
  await page.getByRole('button', { name: '임시저장', exact: true }).click();
  await page.waitForURL(url => /\/admin\/contents\/[^/]+$/.test(url.pathname) && !url.pathname.endsWith('/new'));
  assert(!page.url().endsWith('/new'), '초안 저장 후 ID 경로 이동 실패');
  const savedURL = page.url();
  await page.reload();
  await page.getByRole('textbox', { name: '콘텐츠 제목', exact: true }).waitFor();
  assert(await page.getByRole('textbox', { name: '콘텐츠 제목', exact: true }).inputValue() === '브라우저 검증 · SUMIF 실습', '저장된 제목 복원 실패');
  await page.getByText('qa-demo.mp4', { exact: true }).waitFor();
  await page.getByRole('button', { name: '학습 화면 미리보기' }).click();
  await page.getByRole('dialog').waitFor();
  await page.getByRole('radio', { name: 'SUMIF', exact: true }).check();
  await page.getByRole('button', { name: '답안 확인' }).click();
  await page.getByText('정답입니다.', { exact: true }).waitFor();
  assert(await page.locator('.preview-video').evaluate(video => video.duration > 0), '영상 Blob 복원 실패');
  await page.screenshot({ path: 'output/playwright/05-learning-preview.png', fullPage: true });
  await page.getByRole('button', { name: '닫기', exact: true }).click();
  await page.getByRole('button', { name: '공개하기', exact: true }).click();
  await page.getByRole('button', { name: '비공개로 변경', exact: true }).waitFor();
  await page.screenshot({ path: 'output/playwright/06-content-editor-published.png', fullPage: true });
  await page.getByRole('button', { name: '비공개로 변경', exact: true }).click();
  await page.getByRole('button', { name: '공개하기', exact: true }).waitFor();
  await page.reload();
  await page.getByText('비공개', { exact: true }).waitFor();
  console.log(JSON.stringify({ result: 'passed', savedURL, scenarios: ['과정 등록·수정·복원', '누락 항목 공개 차단', '파일 형식 거절', 'MP4·PNG·자료 업로드', '초안·파일 새로고침 복원', '영상·퀴즈 미리보기', '공개·비공개 전환'] }));
}
