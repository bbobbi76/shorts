async (page) => {
  const assert = (value, message) => { if (!value) throw new Error(message); };
  if (new URL(page.url()).pathname === '/admin/contents') { await page.getByRole('heading', { name: /^학습 콘텐츠 \d+$/ }).waitFor(); await page.locator('.table-edit').first().click(); }
  await page.getByRole('textbox', { name: '콘텐츠 제목', exact: true }).waitFor();
  const originalURL = page.url();
  await page.getByRole('textbox', { name: '콘텐츠 제목', exact: true }).fill('오류·만료 후에도 유지되는 SUMIF 콘텐츠');
  await page.getByRole('button', { name: '연결 및 시연 설정' }).click();
  await page.getByRole('button', { name: '다음 저장 실패', exact: true }).click();
  await page.getByRole('button', { name: '수정 저장', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: '저장 실패를 재현' }).waitFor();
  assert(await page.getByRole('textbox', { name: '콘텐츠 제목', exact: true }).inputValue() === '오류·만료 후에도 유지되는 SUMIF 콘텐츠', '저장 실패 시 입력 유지 실패');
  await page.screenshot({ path: 'output/playwright/07-save-error.png', fullPage: true });
  await page.getByRole('button', { name: '수정 저장', exact: true }).click();
  await page.getByRole('status').filter({ hasText: '콘텐츠가 저장되었습니다.' }).waitFor();
  await page.getByRole('button', { name: '연결 및 시연 설정' }).click();
  await page.getByRole('button', { name: '다음 업로드 실패', exact: true }).click();
  const previousFileName = await page.getByLabel('실습 예제 파일 파일 선택').locator('..').locator('.uploaded>strong').textContent();
  const replacement = { name: '재시도예제.txt', mimeType: 'text/plain', buffer: Buffer.from('업로드 재시도 검증용 자료') };
  await page.getByLabel('실습 예제 파일 파일 선택').setInputFiles(replacement);
  await page.getByRole('alert').filter({ hasText: '업로드 실패를 재현' }).waitFor();
  assert(await page.getByText(previousFileName, { exact: true }).isVisible(), '업로드 실패 시 기존 파일 보존 실패');
  await page.getByLabel('실습 예제 파일 파일 선택').setInputFiles(replacement);
  await page.getByText('재시도예제.txt', { exact: true }).waitFor();
  await page.getByLabel('학습 목표', { exact: true }).fill('로그인 만료 전 작성한 학습 목표');
  await page.getByRole('button', { name: '연결 및 시연 설정' }).click();
  await page.getByRole('button', { name: '로그인 만료 재현', exact: true }).click();
  await page.getByRole('dialog').getByRole('heading', { name: '관리자 로그인' }).waitFor();
  await page.screenshot({ path: 'output/playwright/08-session-expired.png', fullPage: true });
  await page.getByRole('button', { name: '관리자로 입장' }).click();
  assert(await page.getByLabel('학습 목표', { exact: true }).inputValue() === '로그인 만료 전 작성한 학습 목표', '재로그인 시 폼 복원 실패');
  await page.getByRole('button', { name: '연결 및 시연 설정' }).click();
  await page.getByRole('button', { name: '권한 없음 재현', exact: true }).click();
  await page.getByRole('heading', { name: '관리자 권한이 필요해요' }).waitFor();
  await page.screenshot({ path: 'output/playwright/09-forbidden.png', fullPage: true });
  await page.getByRole('button', { name: '다른 계정으로 로그인' }).click();
  await page.getByRole('button', { name: '관리자로 입장' }).click();
  assert(await page.getByLabel('학습 목표', { exact: true }).inputValue() === '로그인 만료 전 작성한 학습 목표', '권한 안내 복귀 시 입력 유지 실패');
  await page.getByRole('link', { name: '콘텐츠 목록', exact: true }).click();
  await page.getByRole('heading', { name: '저장하지 않은 변경사항', exact: true }).waitFor();
  await page.getByRole('button', { name: '계속 작성', exact: true }).click();
  assert(page.url() === originalURL, '미저장 이동 취소 실패');
  await page.getByRole('button', { name: '수정 저장', exact: true }).click();
  await page.getByRole('status').filter({ hasText: '콘텐츠가 저장되었습니다.' }).waitFor();
  const widths = [];
  await page.waitForTimeout(600);
  await page.locator('.loading').waitFor({ state: 'hidden' });
  for (const width of [390, 768, 1440]) {
    await page.setViewportSize({ width, height: 960 });
    const layout = await page.evaluate(() => ({ viewport: innerWidth, documentWidth: document.documentElement.scrollWidth }));
    assert(layout.documentWidth <= width, `편집 화면 가로 넘침: ${JSON.stringify(layout)}`);
    await page.screenshot({ path: `output/playwright/10-editor-${width}.png`, fullPage: true });
    widths.push(layout);
  }
  await page.getByRole('link', { name: '콘텐츠 목록', exact: true }).click();
  await page.getByRole('heading', { name: /^학습 콘텐츠 \d+$/ }).waitFor();
  await page.getByRole('textbox', { name: '콘텐츠 제목 검색' }).fill('존재하지않는검색어');
  await page.getByRole('heading', { name: '표시할 콘텐츠가 없어요' }).waitFor();
  await page.screenshot({ path: 'output/playwright/11-empty-search.png', fullPage: true });
  await page.getByRole('button', { name: '검색 조건 초기화' }).click();
  await page.setViewportSize({ width: 390, height: 800 });
  const mobile = await page.evaluate(() => ({ viewport: innerWidth, documentWidth: document.documentElement.scrollWidth }));
  assert(mobile.documentWidth <= 390, '모바일 목록 가로 넘침');
  await page.screenshot({ path: 'output/playwright/12-content-list-mobile.png', fullPage: true });
  await page.getByRole('button', { name: '메뉴 열기' }).click();
  await page.getByRole('button', { name: '연결 및 시연 설정' }).waitFor({ state: 'visible' });
  await page.getByRole('button', { name: '메뉴 닫기' }).click();
  await page.setViewportSize({ width: 1440, height: 1000 });
  console.log(JSON.stringify({ result: 'passed', widths, scenarios: ['저장 실패·재시도', '업로드 실패·기존 파일 유지·동일 파일 재시도', '로그인 만료·재로그인 입력 유지', '권한 없음·복귀', '미저장 이동 취소', '390·768·1440 편집 화면', '검색 빈 결과·초기화', '390 목록·메뉴 열기/닫기'] }));
}
