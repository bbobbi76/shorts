async (page) => {
  const assert = (value, message) => { if (!value) throw new Error(message); };
  await page.setViewportSize({ width: 390, height: 800 });
  await page.goto('http://127.0.0.1:5173/admin/contents');
  await page.getByRole('heading', { name: /^학습 콘텐츠 \d+$/ }).waitFor();
  const check = async label => { const layout = await page.evaluate(() => ({ viewport: innerWidth, documentWidth: document.documentElement.scrollWidth })); assert(layout.documentWidth <= layout.viewport, `${label}: ${JSON.stringify(layout)}`); return layout; };
  await check('390 목록');
  await page.screenshot({ path: 'output/playwright/12-content-list-mobile.png', fullPage: true });
  await page.getByRole('button', { name: '메뉴 열기' }).click();
  await page.getByRole('button', { name: '연결 및 시연 설정' }).waitFor({ state: 'visible' });
  await page.getByRole('link', { name: '과정 관리', exact: true }).click();
  await page.getByRole('heading', { name: '신입 직장인을 위한 엑셀 기초' }).waitFor();
  await check('390 과정 목록');
  await page.screenshot({ path: 'output/playwright/14-courses-mobile.png', fullPage: true });
  await page.locator('.course-table .table-edit').first().click();
  await page.getByLabel('과정명').waitFor();
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.screenshot({ path: 'output/playwright/21-course-edit-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await check('390 과정 수정');
  await page.screenshot({ path: 'output/playwright/22-course-edit-mobile.png', fullPage: true });
  await page.getByRole('link', { name: '과정 목록', exact: true }).click();
  await page.getByRole('link', { name: '과정 등록', exact: true }).click();
  await page.getByLabel('과정명').waitFor();
  await check('390 과정 입력');
  await page.screenshot({ path: 'output/playwright/15-course-form-mobile.png', fullPage: true });
  await page.getByRole('button', { name: '메뉴 열기' }).click();
  await page.getByRole('link', { name: '콘텐츠 관리', exact: true }).click();
  await page.locator('.page-heading').getByRole('link', { name: '콘텐츠 등록', exact: true }).click();
  await page.getByRole('textbox', { name: '콘텐츠 제목', exact: true }).waitFor();
  await check('390 콘텐츠 등록');
  await page.screenshot({ path: 'output/playwright/23-content-create-mobile.png', fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.screenshot({ path: 'output/playwright/24-content-create-desktop.png', fullPage: true });
  await page.getByRole('link', { name: '콘텐츠 목록', exact: true }).click();
  await page.locator('.table-edit').first().click();
  await page.getByRole('textbox', { name: '콘텐츠 제목', exact: true }).waitFor();
  await page.waitForTimeout(600);
  await page.locator('.loading').waitFor({ state: 'hidden' });
  const widths = [];
  for (const width of [390, 768, 1440]) {
    await page.setViewportSize({ width, height: 960 });
    widths.push(await check(`${width} 편집`));
    await page.screenshot({ path: `output/playwright/10-editor-${width}.png`, fullPage: true });
  }
  await page.getByRole('button', { name: '학습 화면 미리보기' }).click();
  await page.setViewportSize({ width: 390, height: 800 });
  await page.getByRole('dialog').waitFor();
  await check('390 미리보기');
  await page.screenshot({ path: 'output/playwright/16-preview-mobile.png', fullPage: true });
  await page.getByRole('button', { name: '닫기', exact: true }).click();
  await page.getByRole('link', { name: '콘텐츠 목록', exact: true }).click();
  await page.getByRole('textbox', { name: '콘텐츠 제목 검색' }).fill('존재하지않는검색어');
  await page.getByRole('heading', { name: '표시할 콘텐츠가 없어요' }).waitFor();
  await page.getByRole('button', { name: '검색 조건 초기화' }).click();
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.screenshot({ path: 'output/playwright/17-content-list-final.png', fullPage: true });
  console.log(JSON.stringify({ result: 'passed', widths, scenarios: ['390 목록·과정 목록·과정 입력·미리보기', '390·768·1440 편집 화면', '모바일 메뉴 열기·화면 이동', '검색 빈 결과·초기화'] }));
}
