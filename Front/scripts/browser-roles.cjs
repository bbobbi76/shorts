  await page.getByText('qa-demo.mp4',{exact:true}).waitFor();
  await page.getByRole('button',{name:'공개하기',exact:true}).click();
  await page.getByRole('button',{name:'비공개로 변경',exact:true}).waitFor();
  const adminURL=page.url(); const id=new URL(adminURL).pathname.split('/').pop();
  await page.getByRole('link',{name:'사용자 화면 보기',exact:true}).click();
  await page.getByRole('link',{name:'과정 보기',exact:true}).first().click();
  await page.getByRole('link',{name:/관리자·사용자 분리 확인 영상/}).click();
