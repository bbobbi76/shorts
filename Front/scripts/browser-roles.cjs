  const assert = (value, message) => { if (!value) throw new Error(message); };
  await page.goto('http://127.0.0.1:5173/');
  await page.setViewportSize({width:1440,height:1000});
  await page.getByRole('heading',{name:'이용할 화면을 선택하세요'}).waitFor();
  await page.screenshot({path:'output/playwright/30-role-selection.png',fullPage:true});
  await page.getByRole('link',{name:'사용자로 입장'}).click();
  await page.getByRole('heading',{name:'과정 탐색',exact:true}).waitFor();
