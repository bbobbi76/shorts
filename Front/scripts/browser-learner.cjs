  await page.getByRole('navigation', { name: '사용자 메뉴' }).getByRole('link', { name: '내 학습 기록' }).click();
  await page.getByRole('heading', { name: '검증_조건별 합계', exact: true }).waitFor();
  await page.getByRole('link', { name: '이어서 학습하기', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('video')?.readyState >= 1);
  assert(await page.locator('video').evaluate(video => video.currentTime >= 1), 'Saved resume position failed');
  await page.getByRole('link', { name: '다음 영상', exact: true }).click();
  await page.getByRole('heading', { name: '검증_필터 사용하기', exact: true }).waitFor();
  assert(await page.getByText('이 영상에 등록된 자막이 없습니다.').count() === 1, 'Missing transcript not handled');
  await page.setViewportSize({ width: 390, height: 844 });
  assert(await page.locator('video').evaluate(video => video.getBoundingClientRect().height <= video.parentElement.getBoundingClientRect().height + 1), 'Mobile video clipped');
  await page.screenshot({ path: 'output/playwright/learner-lesson-mobile.png', fullPage: true });
