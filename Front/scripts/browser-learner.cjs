  await page.getByRole('textbox', { name: '기억할 내용이나 실습한 내용을 적어보세요' }).fill('SUM은 범위를 더한다. 다음에는 필터를 복습한다.');
  await page.getByRole('status').filter({ hasText: '이 브라우저에 저장했습니다.' }).waitFor();
  await page.locator('video').evaluate(async video => { video.muted = true; await video.play(); video.currentTime = 1.1; video.pause(); });
  await page.waitForFunction(() => Object.keys(localStorage).some(key => key.startsWith('workfit-learning-v1:') && JSON.parse(localStorage.getItem(key)).some(item => item.position >= 1)));
  await page.reload();
  await page.waitForFunction(() => document.querySelector('video')?.readyState >= 1);
  // Explicit search timestamp remains authoritative over the stored playback position.
  assert(await page.locator('video').evaluate(video => Math.abs(video.currentTime - 1) < 0.2), 'Explicit timestamp ignored');
  await page.getByRole('tab', { name: '학습 메모', exact: true }).click();
  assert((await page.getByRole('textbox', { name: '기억할 내용이나 실습한 내용을 적어보세요' }).inputValue()).includes('SUM은'), 'Note restore failed');
  await page.getByRole('complementary', { name: '과정의 다른 영상' }).getByRole('link', { name: /01 검증_조건별 합계/ }).waitFor();
  await page.waitForFunction(() => { const video = document.querySelector('video'); return video && !video.seeking && video.readyState >= 2; });
