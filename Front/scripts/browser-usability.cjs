async (page) => {
  const assert = (value, message) => { if (!value) throw new Error(message); };
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto('http://127.0.0.1:5173/admin/contents');
  await page.getByRole('heading', { name: /^학습 콘텐츠 \d+$/ }).waitFor();
  await page.locator('.skip-link').focus(); await page.keyboard.press('Enter');
  assert(await page.locator('main').evaluate(el => el === document.activeElement), '본문 바로가기 포커스 실패');
  await page.locator('.table-edit').first().click();
  await page.getByRole('textbox', { name: '콘텐츠 제목', exact: true }).waitFor();
  await page.waitForTimeout(500);
  const shortTitle = await page.getByRole('textbox', { name: '콘텐츠 제목', exact: true }).inputValue();
  const longTitle = '엑셀_조건별_매출집계_담당자별_자료검토_'.repeat(5).slice(0, 120);
  await page.getByRole('textbox', { name: '콘텐츠 제목', exact: true }).fill(longTitle);
  const longFile = '부서별_매출집계_검토용_첨부자료_'.repeat(7) + '.txt';
  await page.getByLabel('업무용 템플릿 파일 선택').setInputFiles({ name: longFile, mimeType: 'text/plain', buffer: Buffer.from('긴 파일명 레이아웃 검증') });
  await page.getByText(longFile, { exact: true }).waitFor();
  await page.getByRole('button', { name: '수정 저장', exact: true }).click();
  await page.getByRole('status').filter({ hasText: '콘텐츠가 저장되었습니다.' }).waitFor();
  await page.waitForFunction(() => !document.querySelector('.editor-actionbar button')?.disabled);
  await page.setViewportSize({ width: 390, height: 844 });
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), '390 편집 화면 넘침');
  await page.screenshot({ path: 'output/playwright/18-long-title-file-mobile.png', fullPage: true });
  await page.getByRole('button', { name: '학습 화면 미리보기', exact: true }).focus();
  await page.keyboard.press('Enter');
  await page.getByRole('dialog', { name: '학습 화면 미리보기', exact: true }).waitFor();
  await page.keyboard.press('Escape');
  assert(await page.getByRole('button', { name: '학습 화면 미리보기', exact: true }).evaluate(el => el === document.activeElement), '대화상자 닫기 후 포커스 복원 실패');
  const menu = page.getByRole('button', { name: '메뉴 열기', exact: true });
  await menu.focus(); await page.keyboard.press('Enter');
  assert(await menu.getAttribute('aria-expanded') === 'true', '메뉴 확장 상태 누락');
  assert(await page.locator('#admin-sidebar').evaluate(el => el.contains(document.activeElement)), '메뉴 진입 포커스 실패');
  const navItems = page.locator('#admin-sidebar a[href], #admin-sidebar button:not([disabled])');
  await navItems.last().focus(); await page.keyboard.press('Tab');
  assert(await navItems.first().evaluate(el => el === document.activeElement), '메뉴 Tab 순환 실패');
  await page.keyboard.press('Escape');
  assert(await menu.evaluate(el => el === document.activeElement), '메뉴 닫기 후 포커스 복원 실패');
  assert(await page.locator('#admin-sidebar').evaluate(el => el.inert), '닫힌 모바일 메뉴의 포커스 차단 실패');
  await page.getByRole('link', { name: '콘텐츠 목록', exact: true }).click();
  await page.getByRole('textbox', { name: '콘텐츠 제목 검색', exact: true }).fill(longTitle);
  await page.getByRole('link', { name: `${longTitle} 수정`, exact: true }).waitFor();
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), '390 긴 제목 목록 넘침');
  await page.screenshot({ path: 'output/playwright/19-long-title-list-mobile.png', fullPage: true });
  assert(await page.locator('tbody .mobile-meta .badge').isVisible(), '모바일 목록 상태 문구 누락');
  await page.getByRole('button', { name: '공개', exact: true }).click();
  await page.getByRole('heading', { name: '표시할 콘텐츠가 없어요', exact: true }).waitFor();
  await page.getByRole('button', { name: '검색 조건 초기화', exact: true }).click();
  await page.getByRole('link', { name: `${longTitle} 수정`, exact: true }).click();
  await page.getByRole('textbox', { name: '콘텐츠 제목', exact: true }).waitFor();
  await page.getByRole('textbox', { name: '콘텐츠 제목', exact: true }).fill(shortTitle);
  await page.getByRole('button', { name: '수정 저장', exact: true }).click();
  await page.getByRole('status').filter({ hasText: '콘텐츠가 저장되었습니다.' }).waitFor();
  await page.waitForFunction(() => !document.querySelector('.editor-actionbar button')?.disabled);
  // Verify the upload control exposes a visible focus target, not a hidden tab stop.
  assert(await page.getByLabel('업무용 템플릿 파일 선택').getAttribute('tabindex') === '-1', '숨겨진 파일 입력의 Tab 순서 확인 실패');
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.getByRole('link', { name: '콘텐츠 목록', exact: true }).click();
  await page.getByRole('heading', { name: /^학습 콘텐츠 \d+$/ }).waitFor();
  console.log(JSON.stringify({ result: 'passed', scenarios: ['키보드 본문 바로가기', '390px 긴 제목·파일명', '미리보기 Escape·포커스 복원', '모바일 메뉴 Tab 순환·Escape·inert', '상태 문구·필터 조합', '숨겨진 파일 입력 Tab 제외'] }));
}
